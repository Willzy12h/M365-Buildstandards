using System.Net;
using System.Security.Cryptography;
using System.Text;
using BuildStandard.Core;
using BuildStandard.Core.Configuration;
using BuildStandard.Core.Json;
using BuildStandard.Core.Models;
using BuildStandard.Engine.Reports;
namespace BuildStandard.Engine.Standards.Authoring;

public sealed record CandidateExportFiles(string Catalogue, string Draft, string Comparison, string Checksums);
/// <summary>Fresh local outputs only, using the existing report directory and create-new/readback convention.</summary>
public sealed class CandidateLocalOutputs(ToolkitPaths paths, CandidateAuthoringService authoring)
{
    public string SaveDraft(StandardCandidateDraft draft, CancellationToken ct = default)
    {
        var json = CandidateDraftCodec.Serialize(draft);
        _ = CandidateDraftCodec.Read(json);
        var name = "standard-draft-" + Guid.NewGuid().ToString("N") + ".json";
        WriteSet([(name, json)], ct, null);
        return Path.Combine(paths.ReportsDirectory, name);
    }
    public CandidateExportFiles Export(StandardCandidateDraft draft, CandidateValidationTicket ticket, CancellationToken ct = default, IProgress<string>? progress = null)
    {
        ct.ThrowIfCancellationRequested();
        var snapshot = CandidateDraftCodec.Read(CandidateDraftCodec.Serialize(draft));
        var catalogue = ticket.RequireCurrent(authoring, snapshot);
        var prefix = "standard-candidate-" + Guid.NewGuid().ToString("N");
        var files = new CandidateExportFiles(prefix + ".json", prefix + ".draft.json", prefix + ".comparison.html", prefix + ".sha256");
        var content = new List<(string Name, string Content)>
        {
            (files.Catalogue, ToolkitJson.Serialize(catalogue)),
            (files.Draft, CandidateDraftCodec.Serialize(snapshot)),
            (files.Comparison, Comparison(snapshot, catalogue))
        };
        content.Add((files.Checksums, string.Join('\n', content.Select(f => CanonicalJson.Sha256Hex(f.Content) + "  " + f.Name)) + "\n"));
        WriteSet(content, ct, progress);
        return new(Path.Combine(paths.ReportsDirectory, files.Catalogue), Path.Combine(paths.ReportsDirectory, files.Draft),
            Path.Combine(paths.ReportsDirectory, files.Comparison), Path.Combine(paths.ReportsDirectory, files.Checksums));
    }
    private void WriteSet(IReadOnlyList<(string Name, string Content)> files, CancellationToken ct, IProgress<string>? progress)
    {
        ct.ThrowIfCancellationRequested();
        var bytes = files.Select(f => (f.Name, Bytes: new UTF8Encoding(false, true).GetBytes(f.Content))).ToArray();
        if (bytes.Any(f => f.Bytes.Length > CandidateDraftCodec.MaximumBytes)) throw new ConfigurationException("A candidate output exceeds the 8 MiB bound; nothing was saved.");
        ReportEnvelopeDispatcher.RefuseLinks(Path.Combine(paths.ReportsDirectory, "candidate-output"));
        Directory.CreateDirectory(paths.ReportsDirectory);
        var owned = new List<string>();
        try
        {
            foreach (var file in bytes)
            {
                ct.ThrowIfCancellationRequested();
                var target = Path.Combine(paths.ReportsDirectory, file.Name);
                ReportEnvelopeDispatcher.RefuseLinks(target);
                using (var output = new FileStream(target, FileMode.CreateNew, FileAccess.ReadWrite, FileShare.None))
                {
                    owned.Add(target);
                    output.Write(file.Bytes); output.Flush(flushToDisk: true); output.Position = 0;
                    var actual = Convert.ToHexString(SHA256.HashData(output)).ToLowerInvariant();
                    if (actual != CanonicalJson.Sha256Hex(file.Bytes)) throw new IntegrityException("Local candidate output readback did not match the generated bytes.");
                }
                progress?.Report($"Saved local candidate file {owned.Count}/{bytes.Length}.");
                ct.ThrowIfCancellationRequested();
            }
        }
        catch (Exception failure)
        {
            var remaining = new List<string>();
            foreach (var file in owned)
            {
                try { ReportEnvelopeDispatcher.RefuseLinks(file); File.Delete(file); }
                catch (Exception ex) when (ex is IOException or UnauthorizedAccessException or ToolkitException) { remaining.Add(file); }
            }
            if (remaining.Count != 0) throw new IOException("Candidate output failed; cleanup could not remove these incomplete local files: " + string.Join(", ", remaining), failure);
            throw;
        }
    }
    private static string Comparison(StandardCandidateDraft draft, StandardCatalogue candidate)
    {
        static string E(string value) => WebUtility.HtmlEncode(value);
        static string V(System.Text.Json.Nodes.JsonNode? value) => E(CanonicalJson.Serialize(value));
        var html = new StringBuilder("<!doctype html><html lang=\"en-GB\"><meta charset=\"utf-8\"><meta http-equiv=\"Content-Security-Policy\" content=\"default-src 'none'; style-src 'unsafe-inline'\"><title>Candidate comparison</title><style>body{font:16px system-ui;margin:2rem}table{border-collapse:collapse;width:100%}td,th{border:1px solid #888;padding:.6rem;text-align:left;vertical-align:top}pre{white-space:pre-wrap;overflow-wrap:anywhere}code{overflow-wrap:anywhere}</style><body><h1>");
        html.Append(E(draft.Title)).Append("</h1><p>Local candidate — not a published standard, tenant assessment or execution approval.</p><p>Baseline: ")
            .Append(E(draft.Baseline.Release)).Append(" · exact file SHA-256 <code>").Append(E(draft.Baseline.FileSha256))
            .Append("</code></p><p>Candidate: ").Append(E(candidate.Release)).Append(" · draft SHA-256 <code>").Append(E(draft.ContentDigest)).Append("</code></p><h2>Configuration comparison</h2>");
        if (draft.Changes.Count == 0) html.Append("<p>No configuration changes selected.</p>");
        else
        {
            html.Append("<table><tr><th>Control</th><th>Setting</th><th>Original</th><th>Proposed</th></tr>");
            foreach (var change in draft.Changes)
                html.Append("<tr><td>").Append(E(candidate.FindControl(change.ControlId)?.Name ?? change.ControlId)).Append("<br><code>").Append(E(change.ControlId))
                    .Append("</code></td><td><code>").Append(E(change.Path)).Append("</code></td><td><pre>").Append(V(change.ExpectedOriginal))
                    .Append("</pre></td><td><pre>").Append(V(change.Proposed)).Append("</pre></td></tr>");
            html.Append("</table>");
        }
        html.Append("<h2>Assignment observations — source claims only</h2><p>Assignments are not applied by this editor. Missing observations are unknown, not an empty assignment inventory.</p>");
        foreach (var item in draft.AssignmentObservations)
            html.Append("<p>").Append(E(item.ControlId)).Append(" · ").Append(E(item.Status)).Append(" · ").Append(E(item.Detail)).Append(" · source <code>").Append(E(item.SourceSha256)).Append("</code></p>");
        html.Append("<h2>Source imports</h2><p>Digests detect changes; they do not authenticate the source or verify Microsoft behaviour.</p>");
        foreach (var item in draft.Imports)
            html.Append("<p>").Append(E(item.ControlId)).Append(" · ").Append(E(item.PolicyType)).Append(" · <code>").Append(E(item.Sha256)).Append("</code></p>");
        return html.Append("<p>Changed defaults have no inherited vendor-review date. Review current vendor guidance. Use the separate reviewed standard-publication process before treating this as a released successor.</p></body></html>").ToString();
    }
}
