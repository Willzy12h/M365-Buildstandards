using System.Security.Cryptography;
using System.Text;
using BuildStandard.Core;

namespace BuildStandard.Engine.Reports;

public sealed partial class ReportExporter
{
    public string ExportDeploymentCoverage(DeploymentCoverageEvidence capture,ExportFormat format)
    {
        var report=capture.Metadata; // Strict revalidation before generating any output.
        var bytes=format switch
        {
            ExportFormat.Html=>Encoding.UTF8.GetBytes(DeploymentCoverageDocuments.Html(capture,_companyName)),
            ExportFormat.Json=>DeploymentCoverageBundle.Write(capture),
            ExportFormat.Csv=>CsvWriter.ZipSheets(DeploymentCoverageDocuments.Sheets(capture)),
            ExportFormat.Xlsx=>XlsxWriter.Write(DeploymentCoverageDocuments.Sheets(capture)),
            _=>throw new ConfigurationException("Coverage observations exports as html, original JSON ZIP, csv or xlsx only.")
        };
        var extension=format switch{ExportFormat.Html=>"html",ExportFormat.Json=>"json.zip",ExportFormat.Csv=>"csv.zip",_=>"xlsx"};
        var file=Target("coverage-"+(capture.IsHistorical?"historical-unverified-":"")+report.Id+"-"+Guid.NewGuid().ToString("N"),report.TenantId,report.CompletedAt,extension);
        var created=false;
        try
        {
            using var output=new FileStream(file,FileMode.CreateNew,FileAccess.ReadWrite,FileShare.None);
            created=true;output.Write(bytes);output.Flush(flushToDisk:true);output.Position=0;
            if(!SHA256.HashData(output).AsSpan().SequenceEqual(SHA256.HashData(bytes)))
                throw new IntegrityException("The coverage export readback differs from the generated bytes. No verified export is claimed.");
            return file;
        }
        catch
        {
            if(created){try{File.Delete(file);}catch(IOException){}catch(UnauthorizedAccessException){}}
            throw;
        }
    }
}
